def _fill_placeholders(template: str, brand_cfg: BrandConfig) -> str:
    """把模板里的 {brand_name} {target_age_str} {target_size_str} 替换掉。"""
    age_str = ""
    size_str = ""
    if brand_cfg.target_age_range:
        lo, hi = brand_cfg.target_age_range
        age_str = f"{lo}-{hi}岁"
    if brand_cfg.target_size_range:
        lo, hi = brand_cfg.target_size_range
        size_str = f"{lo}-{hi}码"

    return template.replace("{brand_name}", brand_cfg.brand_name) \
                   .replace("{target_age_str}", age_str or "未标注") \
                   .replace("{target_size_str}", size_str or "未标注")


def assemble_domain_knowledge(brand_cfg: BrandConfig) -> Optional[str]:
    """组装完整的品牌品类专业知识文本。

    优先级：base 模板（按 industry_segment）→ 品牌专属 overlay（brand_domain_knowledge）

    Returns:
        完整文本 str；如果 base 和 overlay 都没有 → 返回 None（prompt 走 generic fallback）
    """
    # 1. 拿 base 模板
    template = SEGMENT_TEMPLATES.get(brand_cfg.industry_segment or "")

    if template is None and not brand_cfg.brand_domain_knowledge:
        # 没模板也没 brand overlay → 返回 None 让下游 generic fallback
        return None

    # 2. 有模板就用（填充占位符）；没模板但有 brand overlay 也能工作
    if template is not None:
        base_text = _fill_placeholders(template, brand_cfg)
    else:
        base_text = None

    # 3. 叠加品牌专属 knowledge
    overlay = brand_cfg.brand_domain_knowledge
    if overlay:
        overlay_block = f"""

════════════════════════════════════════════════════
【{brand_cfg.brand_name} 品牌专属补充知识（差异化定位、核心卖点、独有反模式）】
════════════════════════════════════════════════════
{overlay.strip()}
"""
    else:
        overlay_block = None

    # 4. 组装
    if base_text and overlay_block:
        return base_text + overlay_block
    if base_text:
        return base_text
    if overlay_block:
        return overlay.lstrip("\n")

    return None


